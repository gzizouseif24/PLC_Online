#!/usr/bin/env python3
"""Table "code de type -> reference + nom" des modules S7-300, tiree des fichiers GSDML ET200M
de STEP 7. Dans ces fichiers chaque module a un ModuleIdentNumber : c'est le code que la CPU
donne dans la SZL 0D91 (9FC3, AFD0...).

    python research/siemens/extraire_modules.py
    python research/siemens/extraire_modules.py "C:\\...\\S7DATA\\GSD"      (autre dossier)

Lecture seule pour les fichiers Siemens. Ecrit plc_online/protocols/s7_modules.py (references et
noms courts seulement), puis affiche les codes du banc pour verifier.
"""
import glob
import os
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_DIR = r"C:\Program Files (x86)\Siemens\Step7\S7DATA\GSD"
OUT = Path(__file__).resolve().parents[2] / "plc_online" / "protocols" / "s7_modules.py"
BENCH = [0x9FC3, 0xAFD0, 0xAFD8, 0xAFC8]


def local(tag):
    return tag.rsplit("}", 1)[-1]


def parse_gsdml(path):
    """-> {code: {(order, name), ...}} for every ModuleItem of one GSDML file."""
    root = ET.parse(path).getroot()
    texts = {}
    for el in root.iter():
        if local(el.tag) == "PrimaryLanguage":
            for t in el:
                if local(t.tag) == "Text":
                    texts[t.get("TextId")] = t.get("Value", "")
            break
    table = {}
    for item in root.iter():
        if local(item.tag) not in ("ModuleItem", "SubmoduleItem", "VirtualSubmoduleItem"):
            continue
        ident = item.get("ModuleIdentNumber") or item.get("SubmoduleIdentNumber")
        if not ident:
            continue
        try:
            code = int(ident, 0)
        except ValueError:
            continue
        order = name = ""
        for el in item.iter():
            t = local(el.tag)
            if t == "OrderNumber" and not order:
                order = el.get("Value", "").strip()
            elif t == "Name" and not name:
                name = texts.get(el.get("TextId"), "").strip()
            if order and name:
                break
        if order or name:
            table.setdefault(code, set()).add((order, name))
    return table


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DIR
    files = sorted(glob.glob(os.path.join(folder, "*")))
    files = [f for f in files if f.lower().endswith(".xml") and "et200m" in os.path.basename(f).lower()]
    if not files:
        raise SystemExit(f"Aucun GSDML ET200M dans {folder}")
    merged = {}
    for f in files:
        try:
            for code, entries in parse_gsdml(f).items():
                merged.setdefault(code, set()).update(entries)
        except ET.ParseError as e:
            print(f"   ignore {os.path.basename(f)} ({e})")
    # codes are 16 bits in SZL 0D91: keep those that fit
    merged = {c & 0xFFFF: v for c, v in merged.items() if c <= 0xFFFF or (c >> 16) == 0}
    lines = ['"""S7-300 module type codes (SZL 0D91 solltyp / isttyp) -> (order number, name).',
             "", f"Generated by research/siemens/extraire_modules.py from {len(files)} ET200M GSDML file(s)",
             'of STEP 7. Several modules can share one code."""', "", "MODULES = {"]
    for code in sorted(merged):
        entries = sorted(e for e in merged[code] if e[0])
        if entries:
            lines.append(f"    0x{code:04X}: {entries!r},")
    lines += ["}", "", "", "def module_name(code):",
              '    """Short text for a type code: "6ES7 321-1BH02-0AA0 DI16xDC24V" or ""."""',
              "    entries = MODULES.get(code)",
              "    if not entries:", '        return ""',
              "    order, name = entries[0]",
              '    more = f" (+{len(entries) - 1} autres)" if len(entries) > 1 else ""',
              '    return f"{order} {name}".strip() + more', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(files)} fichiers, {len(merged)} codes -> {OUT}")
    for c in BENCH:
        print(f"   {c:04X} : {sorted(merged.get(c, [])) or 'non trouve'}")


if __name__ == "__main__":
    main()
