#!/usr/bin/env python3
"""Table "reference -> nom court" du catalogue STEP 7 (CPU, modules, CP, FM, esclaves DP), tiree de :
  - S7DATA\\S7HTXT\\S7HNAMEx.NAM : CPU et composants (une langue par lettre ; B par defaut) ;
  - S7DATA\\GSD\\*.xml (GSDML) : modules, nom du catalogue ;
  - S7DATA\\GSD et NSMET\\*.gse (GSD en anglais) : Module="reference nom".
Le premier nom trouve gagne, dans cet ordre.

    python research/siemens/extraire_noms.py
    python research/siemens/extraire_noms.py "C:\\...\\S7HTXT\\S7HNAMEC.NAM"       (autre langue)

Lecture seule pour le fichier Siemens. Ecrit plc_online/protocols/s7_catalogue.py
(references et noms courts seulement).
"""
import glob
import os
import re
import sys
from pathlib import Path

S7DATA = r"C:\Program Files (x86)\Siemens\Step7\S7DATA"
DEFAULT_DIR = os.path.join(S7DATA, "S7HTXT")
ORDER = re.compile(r"\d[A-Z]{2}\d\s?\d{3}-\w{5}-\w{4}")
OUT = Path(__file__).resolve().parents[2] / "plc_online" / "protocols" / "s7_catalogue.py"


def read_text(path):
    raw = Path(path).read_bytes()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff") or raw[1:2] == b"\x00":
        return raw.decode("utf-16", errors="replace")
    return raw.decode("cp1252", errors="replace")


def parse_nam(text):
    """[id] sections with KatEntryName = order number and SHORTNAME = name."""
    names, order = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("["):
            order = None
            continue
        key, _, value = line.partition("=")
        key, value = key.strip().lower(), value.strip()
        if key == "katentryname":
            order = value
        elif key == "shortname" and order and value:
            names.setdefault(order, value)
    return names


def parse_gsd(text):
    """GSD file: Module="6ES7 321-7TH00-0AB0 16DI_NAMUR" -> {order: name}."""
    names = {}
    for m in re.finditer(r'^\s*Module\s*=\s*"([^"]+)"', text, re.MULTILINE):
        o = ORDER.match(m.group(1).strip())
        if o:
            name = m.group(1).strip()[o.end():].strip()
            if name:
                names.setdefault(o.group(), name)
    return names


def gsdml_names(folder):
    """{order: catalog name} from every GSDML file of the folder (same parser as the type codes)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from extraire_modules import parse_gsdml
    names = {}
    for f in sorted(glob.glob(os.path.join(folder, "*.xml")), reverse=True):     # newest first
        try:
            for entries in parse_gsdml(f).values():
                for order, name in entries:
                    if order and name and ORDER.fullmatch(order.strip()):
                        names.setdefault(order.strip(), name)
        except Exception as e:                       # one bad file must not stop the rest
            print(f"   ignore {os.path.basename(f)} ({e})")
    return names


def normalize(order):
    return re.sub(r"\s+", "", order).upper()


def main():
    if len(sys.argv) > 1:
        path = sys.argv[1]
    else:
        files = sorted(glob.glob(os.path.join(DEFAULT_DIR, "S7HNAME*.NAM")))
        if not files:
            raise SystemExit(f"Aucun S7HNAME*.NAM dans {DEFAULT_DIR} : donner le chemin du fichier.")
        path = next((f for f in files if f.upper().endswith("S7HNAMEB.NAM")), files[0])
    s7data = str(Path(path).resolve().parents[1])          # ...\S7DATA\S7HTXT\file -> ...\S7DATA
    gse = glob.glob(os.path.join(s7data, "GSD", "*.gse")) + glob.glob(os.path.join(s7data, "NSMET", "*.gse"))
    names, seen, counts = {}, set(), []
    for label, found in (("NAM", parse_nam(read_text(path))),
                         ("GSDML", gsdml_names(os.path.join(s7data, "GSD"))),
                         ("GSD", {k: v for f in gse for k, v in parse_gsd(read_text(f)).items()})):
        added = 0
        for k, v in found.items():
            if normalize(k) not in seen:
                seen.add(normalize(k))
                names[k] = v
                added += 1
        counts.append(f"{label} +{added}")
    if not names:
        raise SystemExit(f"Aucune reference trouvee ({path})")
    lines = ['"""STEP 7 catalog: order number (without spaces) -> short name.', "",
             f"Generated by research/siemens/extraire_noms.py from {os.path.basename(path)}, GSDML and GSD files.", '"""', "",
             "NAMES = {"]
    for order in sorted(names, key=normalize):
        lines.append(f"    {normalize(order)!r}: {names[order]!r},")
    lines += ["}", "", "", "def catalog_name(order):",
              '    """Short name for an order number ("6ES7 315-2AF03-0AB0" -> "CPU 315-2 DP") or ""."""',
              '    return NAMES.get("".join((order or "").split()).upper(), "")', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} references ({', '.join(counts)}) -> {OUT}")
    by_key = {normalize(k): v for k, v in names.items()}
    for test in ("6ES7 315-2AF03-0AB0", "6ES7 321-1BL00-0AA0", "6ES7 322-1BH01-0AA0"):
        print(f"   {test} : {by_key.get(normalize(test), 'non trouve')}")


if __name__ == "__main__":
    main()
