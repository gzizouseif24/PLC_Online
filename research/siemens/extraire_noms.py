#!/usr/bin/env python3
"""Table "reference -> nom court" de tout le catalogue STEP 7 (CPU, modules, CP, FM...), tiree de
S7DATA\\S7HTXT\\S7HNAMEx.NAM (une langue par lettre ; on prend B, sinon la premiere trouvee).

    python research/siemens/extraire_noms.py
    python research/siemens/extraire_noms.py "C:\\...\\S7HTXT\\S7HNAMEC.NAM"       (autre langue)

Lecture seule pour le fichier Siemens. Ecrit plc_online/protocols/s7_catalogue.py
(references et noms courts seulement).
"""
import glob
import os
import re
import sys
from pathlib import Path

DEFAULT_DIR = r"C:\Program Files (x86)\Siemens\Step7\S7DATA\S7HTXT"
OUT = Path(__file__).resolve().parents[2] / "plc_online" / "protocols" / "s7_catalogue.py"


def read_text(path):
    raw = Path(path).read_bytes()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff") or raw[1:2] == b"\x00":
        return raw.decode("utf-16", errors="replace")
    return raw.decode("cp1252", errors="replace")


def parse_nam(text):
    """[id] sections with KatEntryName = order number and SHORTNAME = name."""
    names, order = {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("["):
            order = None
            continue
        key, _, value = line.partition("=")
        key, value = key.strip().lower(), value.strip()
        if key == "katentryname":
            order = value
        elif key == "shortname" and order and value:
            names.setdefault(order, value)
    return names


def normalize(order):
    return re.sub(r"\s+", "", order).upper()


def main():
    if len(sys.argv) > 1:
        path = sys.argv[1]
    else:
        files = sorted(glob.glob(os.path.join(DEFAULT_DIR, "S7HNAME*.NAM")))
        if not files:
            raise SystemExit(f"Aucun S7HNAME*.NAM dans {DEFAULT_DIR} : donner le chemin du fichier.")
        path = next((f for f in files if f.upper().endswith("S7HNAMEB.NAM")), files[0])
    names = parse_nam(read_text(path))
    if not names:
        raise SystemExit(f"Aucune entree KatEntryName / SHORTNAME dans {path}")
    lines = ['"""STEP 7 catalog: order number (without spaces) -> short name.', "",
             f"Generated by research/siemens/extraire_noms.py from {os.path.basename(path)}.", '"""', "",
             "NAMES = {"]
    for order in sorted(names, key=normalize):
        lines.append(f"    {normalize(order)!r}: {names[order]!r},")
    lines += ["}", "", "", "def catalog_name(order):",
              '    """Short name for an order number ("6ES7 315-2AF03-0AB0" -> "CPU 315-2 DP") or ""."""',
              '    return NAMES.get("".join((order or "").split()).upper(), "")', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{os.path.basename(path)} : {len(names)} references -> {OUT}")
    for test in ("6ES7 315-2AF03-0AB0", "6ES7 321-1BL00-0AA0", "6ES7 322-1BH01-0AA0"):
        print(f"   {test} : {names.get(test) or dict((normalize(k), v) for k, v in names.items()).get(normalize(test), 'non trouve')}")


if __name__ == "__main__":
    main()
