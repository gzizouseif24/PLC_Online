def event_text(event_id: int) -> str:
    """Text of an event ID, or an empty string when the manual does not list it."""
    if event_id in EVENTS:
        return EVENTS[event_id]
    if event_id >> 12 == 0x8:
        return EVENTS.get(f"8x{event_id & 0xFF:02X}", "")
    return ""
